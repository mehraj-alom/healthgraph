"""Read-model layer: compact deterministic summaries derived from clinical source-of-truth.

PatientDailySummary  – one row per (patient_id, summary_date)
PatientHealthSummary – one row per patient (longitudinal)

These are *derived* caches, never the source of truth.  They can be
rebuilt deterministically from the ClinicalEvent + payload tables at
any time.
"""

import uuid
from datetime import date, datetime
from sqlalchemy import (
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from models.base import Base


class PatientDailySummary(Base):
    """Compact daily read model for a patient.

    One row per (patient_id, summary_date).  Upserted deterministically
    from the ClinicalEvent + payload tables — never generated by an LLM.
    """

    __tablename__ = "patient_daily_summaries"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    patient_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("patients.patient_id", ondelete="CASCADE"),
        nullable=False,
    )
    summary_date: Mapped[date] = mapped_column(Date, nullable=False)

    # Structured sections — only populated when data exists for that section.
    # Each section is a JSONB object with a deterministic shape.
    #
    # vitals:       [{concept_id, value, unit, event_time}]
    # symptoms:     [{concept_id, severity, duration_minutes, notes, event_time}]
    # pain:         [{body_location_id, severity, pain_type, structure_id, event_time}]
    # sleep:        {duration_minutes, sleep_quality, awakenings}
    # nutrition:    {water_ml, meals_count, appetite_level}
    # activities:   [{activity_type, duration_minutes, calories_burned}]
    # medications:  [{medication_name, dosage_value, dosage_unit}]
    # wellbeing:    {overall_wellbeing, energy_level, stress_level}
    # notes:        [{safe_notes, event_time}]
    # observations: [{structure_id, finding_code, finding_display_name,
    #                 visual_severity_score, visual_status, clinical_summary}]
    sections: Mapped[dict] = mapped_column(JSONB, nullable=False, default=dict)

    event_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=datetime.utcnow
    )

    __table_args__ = (
        UniqueConstraint(
            "patient_id",
            "summary_date",
            name="uq_patient_daily_summary",
        ),
        Index("ix_patient_daily_summary_patient_date", "patient_id", "summary_date"),
    )


class PatientHealthSummary(Base):
    """Longitudinal patient-wide read model.

    One row per patient.  Contains compact structured information
    about the patient's overall health picture, derived deterministically
    from clinical source-of-truth records.
    """

    __tablename__ = "patient_health_summaries"

    patient_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("patients.patient_id", ondelete="CASCADE"),
        primary_key=True,
    )

    # current_state: latest body-state findings
    # recent_symptoms: last N distinct symptoms across recent days
    # vital_trends: recent vital values (last N entries per type)
    # sleep_trends: recent sleep entries
    # wellbeing_trends: recent wellbeing entries
    # medication_history: distinct medications seen in recent period
    # recurring_pain: pain areas with frequency/severity summary
    # document_findings: brief summary of available document-derived observations
    # event_totals: aggregate counts by event type
    # summary_date_range: [earliest_date, latest_date] of clinical data
    sections: Mapped[dict] = mapped_column(JSONB, nullable=False, default=dict)

    total_events: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=datetime.utcnow
    )
