import React from "react";
import { Audio } from "@remotion/media";
import { Series, staticFile } from "remotion";
import { KineticHook } from "./KineticHook";
import { DataStreams } from "./DataStreams";
import { CountdownStress } from "./CountdownStress";
import { CalmDashboard } from "./CalmDashboard";
import { DURATION_IN_FRAMES, SCENES } from "./timing";

/**
 * 30s / 900f @ 30fps. The four scenes run back to back with no transitions, so
 * the frame numbers in the brief map 1:1 onto the timeline — the sub-bass drop
 * and the wipe land on the same frame (750) by construction.
 *
 * The score is a single synthesised WAV generated by scripts/generate-audio.mjs
 * from the same tick grid the scenes animate against.
 */
export const HealthGraphAd: React.FC = () => {
  return (
    <>
      <Audio src={staticFile("audio/score.wav")} />

      <Series>
        <Series.Sequence
          name="1 Kinetic hook"
          durationInFrames={SCENES.hook.durationInFrames}
        >
          <KineticHook />
        </Series.Sequence>

        <Series.Sequence
          name="2 Disconnected data streams"
          durationInFrames={SCENES.streams.durationInFrames}
        >
          <DataStreams />
        </Series.Sequence>

        <Series.Sequence
          name="3 Countdown stress"
          durationInFrames={SCENES.countdown.durationInFrames}
        >
          <CountdownStress />
        </Series.Sequence>

        <Series.Sequence
          name="4 Calm dashboard"
          durationInFrames={SCENES.dashboard.durationInFrames}
        >
          <CalmDashboard />
        </Series.Sequence>
      </Series>
    </>
  );
};

export const TOTAL_FRAMES =
  SCENES.hook.durationInFrames +
  SCENES.streams.durationInFrames +
  SCENES.countdown.durationInFrames +
  SCENES.dashboard.durationInFrames;

// Guard the two things that must not silently drift apart.
if (TOTAL_FRAMES !== DURATION_IN_FRAMES) {
  throw new Error(
    `Scene lengths sum to ${TOTAL_FRAMES}, expected ${DURATION_IN_FRAMES}`,
  );
}
